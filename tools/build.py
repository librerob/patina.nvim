"""Generate Lua and terminal ports from palette/*.json (Python 3.11+)."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]

def lua(value, indent=0):
    pad = '  ' * indent
    if isinstance(value, dict):
        return '{\n' + ''.join(f'{pad}  {k} = {lua(v, indent+1)},\n' for k, v in value.items()) + pad + '}'
    if isinstance(value, list):
        return '{ ' + ', '.join(lua(v) for v in value) + ' }'
    return json.dumps(value)

def outputs():
    palettes = {mode: json.loads((ROOT / f'palette/{mode}.json').read_text()) for mode in ('dark', 'light')}
    result = {'lua/verdelle/palette.lua': '-- Generated by tools/build.py. Edit palette/*.json.\nreturn ' + lua(palettes) + '\n'}
    names = ('black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white')
    for mode, data in palettes.items():
        c, ansi = data['colors'], data['ansi']
        kitty = {
            'foreground': c['fg'], 'background': c['bg'],
            'selection_foreground': c['selection_fg'], 'selection_background': c['selection'],
            'cursor': c['cursor'], 'cursor_text_color': c['bg'],
            'url_color': c['type'], 'active_border_color': c['func'], 'inactive_border_color': c['border'],
        }
        kitty.update({f'color{i}': value for i, value in enumerate(ansi)})
        result[f'ports/kitty/verdelle-{mode}.conf'] = '# Generated by tools/build.py\n' + ''.join(f'{k} {v}\n' for k, v in kitty.items())
        sections = {
            'primary': {'background': c['bg'], 'foreground': c['fg']},
            'cursor': {'text': c['bg'], 'cursor': c['cursor']},
            'selection': {'text': c['selection_fg'], 'background': c['selection']},
            'normal': dict(zip(names, ansi[:8])), 'bright': dict(zip(names, ansi[8:])),
        }
        result[f'ports/alacritty/verdelle-{mode}.toml'] = '# Generated by tools/build.py\n' + '\n'.join('[colors.'+section+']\n'+''.join(f'{k} = "{v}"\n' for k, v in values.items()) for section, values in sections.items())
        ghostty = {
            'background': c['bg'], 'foreground': c['fg'],
            'cursor-color': c['cursor'], 'cursor-text': c['bg'],
            'selection-background': c['selection'], 'selection-foreground': c['selection_fg'],
        }
        result[f'ports/ghostty/Verdelle {mode.title()}'] = '# Generated by tools/build.py\n' + ''.join(f'{k} = {v}\n' for k, v in ghostty.items()) + ''.join(f'palette = {i}={v}\n' for i, v in enumerate(ansi))
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail when generated files differ')
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    if stale:
        raise SystemExit('Regenerate with python tools/build.py: ' + ', '.join(stale))
    print('Generated files are current' if args.check else 'Generated Lua palette and six terminal ports')

if __name__ == '__main__':
    main()
