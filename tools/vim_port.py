"""Generate Vim's core groups from Verdelle's Neovim highlight definitions."""
from pathlib import Path
import re


def outputs(palettes):
    source = (Path(__file__).resolve().parents[1] / 'lua/verdelle/highlights.lua').read_text(encoding='utf-8')
    core = source.split('  -- Treesitter')[0]
    extra = {'LspInlayHint', 'LspCodeLens', 'LspCodeLensSeparator',
             'DiffAdd', 'DiffChange', 'DiffDelete', 'DiffText',
             'diffAdded', 'diffRemoved', 'diffChanged', 'diffFile', 'diffLine'}
    definitions = dict(re.findall(r'hl\("(\w+)", \{(.*?)\}\)', source))
    groups = dict(re.findall(r'hl\("(\w+)", \{(.*?)\}\)', core))
    groups.update({name: text for name, text in definitions.items() if name in extra})
    links = dict(re.findall(r'link\("(\w+)", "(\w+)"\)', core))
    # Expand the two compact syntax alias loops in the shared definitions.
    for names, target in re.findall(r'for _, g in ipairs\(\{ (.*?) \}\) do link\(g, "(\w+)"\) end', core):
        links.update({name: target for name in re.findall(r'"(\w+)"', names)})
    assert groups['Normal'].strip() == 'fg = c.variable, bg = c.bg'
    lines = [
        '" Generated by tools/build.py. Vim 8.2+ with truecolor, or gVim.',
        "if has('nvim')", "  lua require('verdelle').load()", '  finish', 'endif', '',
        "if !has('gui_running') && !exists('+termguicolors')",
        "  echoerr 'Verdelle requires truecolor Vim or a GUI'", '  finish', 'endif',
        "if exists('+termguicolors')", '  set termguicolors', 'endif',
        'unlet! g:colors_name', 'highlight clear', "if exists('syntax_on')", '  syntax reset', 'endif',
        "let g:colors_name = 'verdelle'", '',
    ]
    for index, mode in enumerate(('dark', 'light')):
        lines.append("if &background ==# 'dark'" if index == 0 else 'else')
        data = palettes[mode]
        lines += ['  let s:p = {']
        lines += [f"        \\ '{key}': '{color}'," for key, color in data['colors'].items()]
        lines += ['        \\ }', '  let g:terminal_ansi_colors = [']
        lines += ["        \\ " + ', '.join(f"'{color}'" for color in data['ansi'][i:i+4]) + ','
                  for i in range(0, 16, 4)]
        lines += ['        \\ ]']
    lines += ['endif', '',
        'function! s:hi(group, fg, bg, attrs, special) abort',
        "  execute 'highlight' a:group 'guifg=' . a:fg 'guibg=' . a:bg",
        "        \\ 'gui=' . a:attrs 'cterm=' . a:attrs 'guisp=' . a:special",
        'endfunction', '',
    ]
    for name, text in groups.items():
        attrs = dict(part.strip().split(' = ', 1) for part in text.split(',') if part.strip())
        def color(key):
            raw = attrs.get(key)
            if raw is None:
                return "'NONE'"
            assert re.fullmatch(r'c\.\w+', raw), (name, key, raw)
            return 's:p.' + raw[2:]
        flags = [key for key in ('bold', 'underline', 'undercurl', 'strikethrough') if attrs.get(key) == 'true']
        style = "'" + (','.join(flags) if flags else 'NONE') + "'"
        if attrs.get('italic') == 'opts.italic_comments':
            style = "(get(g:, 'verdelle_italic_comments', 0) ? 'italic' : 'NONE')"
        lines.append(f"call s:hi('{name}', {color('fg')}, {color('bg')}, {style}, {color('sp')})")
    lines += [f'highlight! link {name} {target}' for name, target in links.items()]
    lines += ["call s:hi('Terminal', s:p.fg, s:p.bg, 'NONE', 'NONE')",
        "call s:hi('VerdelleControlFlow', s:p.keyword, 'NONE', (get(g:, 'verdelle_bold_control_flow', 0) && &background ==# 'light' ? 'bold' : 'NONE'), 'NONE')",
        'highlight! link Conditional VerdelleControlFlow', 'highlight! link Repeat VerdelleControlFlow',
        'highlight! link Exception VerdelleControlFlow', '', 'delfunction s:hi', 'unlet s:p', '',
    ]
    return {'colors/verdelle.vim': '\n'.join(lines)}
